#!/usr/bin/env node
/**
 * Regenerates the tool reference in README.md (between the TOOLS markers)
 * from the compiled catalog, so the docs always match what the server exposes.
 *
 *   npm run build && npm run docs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildCatalog } from "../dist/tools.js";
import { LEAD_ROUTES, loadMap } from "../dist/map.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const README = path.join(ROOT, "README.md");
const map = loadMap(path.join(ROOT, "api-map.json"));
const catalog = buildCatalog([...LEAD_ROUTES, ...map.routes]);

const esc = (s) => String(s).replace(/\|/g, "\\|");
function section(title, intro, rows) {
  const lines = [`### ${title} (${rows.length})`, "", intro, "", "| ID | Tool name | Description | Endpoint | Enabled when |", "|---|---|---|---|---|"];
  rows.forEach((t, i) =>
    lines.push(`| ${i + 1} | \`${t.name}\` | ${esc(t.description)} | ${t.method === "-" ? "—" : `\`${t.method} ${esc(t.path)}\``} | ${esc(t.gate)} |`),
  );
  return lines.join("\n");
}

const by = (k) => catalog.filter((t) => t.kind === k);
const reads = by("read");
const writes = by("write");
const deletes = by("delete");
const denied = by("denied");
const meta = by("meta");
const block = [
  `<!-- TOOLS:START (generated by scripts/gen-readme-tools.mjs — do not edit by hand) -->`,
  "",
  `**${catalog.length - denied.length} tools**: ${meta.length} meta, ${reads.length} read, ${writes.length} write, ${deletes.length} delete. ` +
    `${denied.length} more mapped routes are denied by policy and never exposed. With default settings ${meta.length + reads.length} tools are live (meta + read).`,
  "",
  section("Meta tools", "Always on. Discovery, health and guarded generic access.", meta),
  "",
  section(
    "Read tools",
    "Read-only (`readOnlyHint: true`). Always on. `GET` routes plus Rails datatable/report queries that are sent as `POST` but only read. Every read tool accepts `response_format` (`markdown` default, or `json`).",
    reads,
  ),
  "",
  section(
    "Write tools",
    "**Mutating.** Registered only when `SINGLEOPS_ENABLE_WRITE=true` (default `false`). Each call is a **dry run by default** and returns the exact request; pass `dry_run: false` to send. Capped at `SINGLEOPS_MAX_WRITES` live writes per run and audited to `audit/`.",
    writes,
  ),
  "",
  section(
    "Delete tools",
    "**Destructive.** Registered only when `SINGLEOPS_ENABLE_DELETE=true` (default `false`). Sending needs `dry_run: false` **and** `confirm: \"DELETE <path>\"` naming the one record.",
    deletes,
  ),
  "",
  section("Denied by policy (never exposed)", "Mapped so you know they exist, but no flag turns them on: they move money, change billing or logins, message customers, or reconfigure the account.", denied),
  "",
  "<!-- TOOLS:END -->",
].join("\n");

const readme = fs.readFileSync(README, "utf8");
const next = readme.replace(/<!-- TOOLS:START[\s\S]*?<!-- TOOLS:END -->/, block);
if (next === readme && !readme.includes("<!-- TOOLS:START")) throw new Error("README.md has no TOOLS markers");
fs.writeFileSync(README, next);
console.log(`README tool reference: ${catalog.length} entries (${reads.length} read, ${writes.length} write, ${deletes.length} delete, ${denied.length} denied, ${meta.length} meta).`);
